# 3. Combined fuzzy heating-and-cooling index
# ============================================================

def plot_fuzzy_index(
    heating_lower=16.0,
    heating_upper=20.0,
    cooling_lower=21.0,
    cooling_upper=24.0,
    filename="fuzzy_heating_cooling_index.png"
):
    """
    Plot the combined fuzzy heating-and-cooling indicator:

        I_1(h) = mu_H(h) ⊕ mu_C(h),

    where ⊕ is the probabilistic sum.
    """

    h = np.linspace(13.5, 26.5, 1200)

    mu_heating = decreasing_cosine(
        h,
        heating_lower,
        heating_upper
    )

    mu_cooling = increasing_cosine(
        h,
        cooling_lower,
        cooling_upper
    )

    fuzzy_index = probabilistic_sum(
        mu_heating,
        mu_cooling
    )

    fig, ax = plt.subplots(figsize=(8, 8))

    # Shade the thermal-comfort region
    ax.axvspan(
        heating_upper,
        cooling_lower,
        color="purple",
        alpha=0.06
    )

    ax.plot(
        h,
        fuzzy_index,
        color="indigo",
        linewidth=3
    )

    format_membership_axis(
        ax,
        xmin=13.5,
        xmax=26.5,
        ymin=-0.28,
        ymax=1.13
    )

    ax.set_xticks(np.arange(14, 27, 2))

    ax.set_title(
        "Fuzzy index",
        color="indigo",
        fontsize=20,
        fontweight="bold",
        pad=20
    )

    # Horizontal guide at membership degree 1
    ax.hlines(
        1,
        heating_lower,
        cooling_upper,
        color="gray",
        linestyle=(0, (4, 4)),
        linewidth=1
    )

    # Threshold lines
    ax.axvline(
        heating_lower,
        color="royalblue",
        linestyle=(0, (4, 4)),
        linewidth=1.2
    )

    ax.axvline(
        heating_upper,
        color="red",
        linestyle=(0, (4, 4)),
        linewidth=1.0,
        alpha=0.65
    )

    ax.axvline(
        cooling_lower,
        color="red",
        linestyle=(0, (4, 4)),
        linewidth=1.0,
        alpha=0.65
    )

    ax.axvline(
        cooling_upper,
        color="seagreen",
        linestyle=(0, (4, 4)),
        linewidth=1.2
    )

    # Active regions
    ax.text(
        14.9,
        0.55,
        "heating\n"
        "demand\n"
        "(active)",
        color="indigo",
        fontsize=15,
        ha="center",
        va="center",
        linespacing=1.6
    )

    ax.text(
        25.2,
        0.55,
        "cooling\n"
        "demand\n"
        "(active)",
        color="indigo",
        fontsize=15,
        ha="center",
        va="center",
        linespacing=1.6
    )

    # Threshold labels
    ax.text(
        heating_lower,
        -0.12,
        r"$L_H$",
        color="royalblue",
        fontsize=18,
        ha="center"
    )

    ax.text(
        cooling_upper,
        -0.12,
        r"$U_C$",
        color="seagreen",
        fontsize=18,
        ha="center"
    )

    comfort_midpoint = 0.5 * (
        heating_upper + cooling_lower
    )

    ax.text(
        comfort_midpoint,
        -0.19,
        "thermally adequate\n"
        "(neither heating nor cooling needed)",
        color="indigo",
        fontsize=14,
        ha="center",
        va="top",
        linespacing=1.5
    )

    fig.text(
        0.5,
        0.01,
        "High values indicate need for heating or cooling;\n"
        "low values indicate thermal adequacy.",
        color="indigo",
        fontsize=15,
        ha="center",
        linespacing=1.5
    )

    fig.subplots_adjust(bottom=0.25)
    fig.savefig(filename, dpi=300, bbox_inches="tight")

    return fig, ax


