def plot_heating_adequacy(
    lower=16.5,
    upper=23.5,
    reference_temperature=20.0,
    filename="heating_adequacy.png"
):
    """
    Plot the decreasing heating membership function.

    Membership is high when the indoor temperature is low.
    """

    h = np.linspace(13.5, 26.0, 1000)
    mu_heating = decreasing_cosine(h, lower, upper)

    fig, ax = plt.subplots(figsize=(8, 8))

    ax.plot(
        h,
        mu_heating,
        color="royalblue",
        linewidth=3
    )

    format_membership_axis(
        ax,
        xmin=13.5,
        xmax=26.0,
        ymin=-0.36,
        ymax=1.13
    )

    ax.set_xticks(np.arange(14, 27, 2))

    # Threshold lines
    ax.axvline(
        lower,
        color="royalblue",
        linestyle=(0, (4, 4)),
        linewidth=1.3
    )

    ax.axvline(
        upper,
        color="royalblue",
        linestyle=(0, (4, 4)),
        linewidth=1.3
    )

    # Reference temperature
    ax.axvline(
        reference_temperature,
        color="red",
        linestyle=(0, (4, 4)),
        linewidth=1.1,
        alpha=0.7
    )

    # Title
    ax.set_title(
        "Heating adequacy",
        color="royalblue",
        fontsize=20,
        fontweight="bold",
        pad=20
    )

    # Threshold labels
    ax.text(
        lower,
        1.07,
        r"$L_H$",
        color="royalblue",
        fontsize=18,
        ha="center"
    )

    ax.text(
        upper,
        1.07,
        r"$U_H$",
        color="royalblue",
        fontsize=18,
        ha="center"
    )

    # Region descriptions
    ax.text(
        15.1,
        0.55,
        "fully\nadequate\n(heating)",
        color="royalblue",
        fontsize=15,
        ha="center",
        va="center",
        linespacing=1.6
    )

    ax.text(
        21.0,
        0.55,
        "transition\nas $h$\nincreases",
        color="royalblue",
        fontsize=15,
        ha="center",
        va="center",
        linespacing=1.6
    )

    ax.text(
        25.0,
        0.55,
        "not\nadequate\n(too warm)",
        color="royalblue",
        fontsize=15,
        ha="center",
        va="center",
        linespacing=1.6
    )

    # Reference-temperature label
    ax.text(
        reference_temperature,
        -0.12,
        rf"$h_H={reference_temperature:g}^{{\circ}}\mathrm{{C}}$",
        color="red",
        fontsize=16,
        ha="center"
    )

    # Transition-width arrow
    arrow_y = -0.25

    ax.annotate(
        "",
        xy=(upper, arrow_y),
        xytext=(lower, arrow_y),
        arrowprops={
            "arrowstyle": "<->",
            "color": "royalblue",
            "linewidth": 1.8
        }
    )

    ax.text(
        (lower + upper) / 2,
        arrow_y - 0.06,
        r"transition width $2\Delta_h$",
        color="royalblue",
        fontsize=15,
        ha="center",
        va="top"
    )

    fig.text(
        0.5,
        0.01,
        "Membership is high when the\n"
        "temperature is sufficiently low.",
        color="royalblue",
        fontsize=15,
        ha="center",
        linespacing=1.5
    )

    fig.subplots_adjust(bottom=0.25)
    fig.savefig(filename, dpi=300, bbox_inches="tight")

    return fig, ax


