import numpy as np
import matplotlib.pyplot as plt


# ============================================================
# Cosine transition membership functions
# ============================================================

def increasing_cosine(x, lower, upper):
    """
    Increasing cosine transition:

        0,                                      x <= lower
        (1 - cos(pi*(x-lower)/(upper-lower)))/2 lower < x < upper
        1,                                      x >= upper
    """
    x = np.asarray(x, dtype=float)
    y = np.zeros_like(x)

    transition = (x > lower) & (x < upper)

    y[transition] = 0.5 * (
        1.0
        - np.cos(
            np.pi
            * (x[transition] - lower)
            / (upper - lower)
        )
    )

    y[x >= upper] = 1.0

    return y


def decreasing_cosine(x, lower, upper):
    """
    Decreasing cosine transition:

        1,                                      x <= lower
        (1 + cos(pi*(x-lower)/(upper-lower)))/2 lower < x < upper
        0,                                      x >= upper
    """
    return 1.0 - increasing_cosine(x, lower, upper)


def probabilistic_sum(a, b):
    """
    Probabilistic t-conorm:

        a ⊕ b = a + b - ab.
    """
    return a + b - a * b


