def format_membership_axis(ax, xmin, xmax, ymin=-0.02, ymax=1.13):
    """Format an axis as a fuzzy-membership graph."""

    ax.set_xlim(xmin, xmax)
    ax.set_ylim(ymin, ymax)

    ax.set_yticks([0, 0.5, 1])
    ax.set_yticklabels(["0", "0.5", "1"])

    ax.spines["top"].set_visible(False)
    ax.spines["right"].set_visible(False)

    ax.tick_params(direction="in", length=4)

    ax.set_ylabel(
        r"$\mu$",
        rotation=0,
        fontsize=20,
        labelpad=15
    )

    ax.set_xlabel(
        r"$h\;({}^{\circ}\mathrm{C})$",
        fontsize=16,
        loc="right"
    )


